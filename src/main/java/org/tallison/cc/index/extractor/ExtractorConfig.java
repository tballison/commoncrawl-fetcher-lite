package org.tallison.cc.index.extractor;

import com.fasterxml.jackson.annotation.JsonCreator;
import com.fasterxml.jackson.annotation.JsonIgnore;
import com.fasterxml.jackson.annotation.JsonIgnoreProperties;
import com.fasterxml.jackson.annotation.JsonProperty;
import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;

import java.io.File;
import java.io.IOException;
import java.nio.file.Path;
import java.nio.file.Paths;
import java.util.concurrent.ThreadLocalRandom;

import org.tallison.cc.index.IndexIterator;
import org.tallison.cc.index.io.BackoffS3Fetcher;
import org.tallison.cc.index.io.TargetPathRewriter;
import org.tallison.cc.index.io.TikaPipes;
import org.tallison.cc.index.selector.RecordSelector;

import org.apache.tika.exception.TikaConfigException;
import org.apache.tika.pipes.api.emitter.StreamEmitter;
import org.apache.tika.pipes.api.fetcher.Fetcher;
import org.apache.tika.utils.StringUtils;

// Tolerate unknown top-level fields -- config files across this repo use a "_comment" key
// as a documentation convention (JSON has no native comment syntax), and this class
// shouldn't crash on that or on future fields it doesn't yet know about.
@JsonIgnoreProperties(ignoreUnknown = true)
public class ExtractorConfig {

    public static String CC_HTTPS_BASE = "https://data.commoncrawl.org";

    public static String CC_S3_BUCKET = "commoncrawl";

    public static String CC_REGION = "us-east-1";

    public static String DEFAULT_FS_DOCS_PATH = "docs";

    public static long DEFAULT_COUNT_TIMEOUT_SECONDS = 1800;

    public static long[] DEFAULT_THROTTLE_SECONDS = new long[] {30, 120, 600, 1800};
    private int numThreads = 2;
    // maximum records to read
    private long maxRecords = -1;

    // maximum files extracted from cc
    private long maxFilesExtracted = -1;
    // maximum files written to 'truncated' logger
    private long maxFilesTruncated = -1;

    private Path indexPathsFile;
    private String targetPathPattern = "";

    private boolean dryRun = false;

    private boolean extractTruncated = false;

    // Not read by this class -- resolved and primed into a system property before this config
    // is parsed, so that log4j2.xml can scope this run's CSV logs to their own subdirectory.
    // See RunLabel. Declared here only so Jackson doesn't reject the JSON key.
    private String runLabel;

    private RecordSelector recordSelector = RecordSelector.ACCEPT_ALL_RECORDS;

    // optional; drives sampling. If absent, load() generates one so the run is reproducible.
    private Long seed;
    // true if seed was generated by load() rather than given in the config
    private boolean seedGenerated;

    // default: logs/<runLabel>/provenance.jsonl and logs/<runLabel>/manifest.json
    private String provenancePath;
    private String manifestPath;

    @JsonIgnore private JsonNode rawConfig;
    @JsonIgnore private ProvenanceWriter provenanceWriter;

    @JsonProperty("indices")
    private IndexIterator indexIterator;

    @JsonProperty("fetcher")
    private FetchConfig fetchConfig;

    @JsonProperty("indexFetcher")
    private FetchConfig indexFileFetchConfig;

    @JsonProperty("docs")
    private EmitConfig emitConfig;

    @JsonProperty("columnarIndex")
    private ColumnarIndexConfig columnarIndexConfig;

    /** Reads the config, keeping the raw JSON for the manifest and resolving the seed. */
    public static ExtractorConfig load(File file) throws IOException {
        ObjectMapper mapper = new ObjectMapper();
        ExtractorConfig config = mapper.readValue(file, ExtractorConfig.class);
        config.rawConfig = mapper.readTree(file);
        config.resolveSeed();
        return config;
    }

    /** Uses the configured seed, else generates one; seeds the record selector either way. */
    public void resolveSeed() {
        if (seed == null) {
            seed = ThreadLocalRandom.current().nextLong();
            seedGenerated = true;
        }
        recordSelector.applySeed(seed);
    }

    public Long getSeed() {
        return seed;
    }

    public void setSeed(Long seed) {
        this.seed = seed;
    }

    public boolean isSeedGenerated() {
        return seedGenerated;
    }

    public JsonNode getRawConfig() {
        return rawConfig;
    }

    public Path getProvenancePath() {
        return pathOrDefault(provenancePath, "provenance.jsonl");
    }

    public void setProvenancePath(String provenancePath) {
        this.provenancePath = provenancePath;
    }

    public Path getManifestPath() {
        return pathOrDefault(manifestPath, "manifest.json");
    }

    public void setManifestPath(String manifestPath) {
        this.manifestPath = manifestPath;
    }

    private static Path pathOrDefault(String configured, String name) {
        if (!StringUtils.isBlank(configured)) {
            return Paths.get(configured);
        }
        return Paths.get("logs", System.getProperty(RunLabel.SYSTEM_PROPERTY, "default"), name);
    }

    /** Shared by all workers; the file is only created on the first write. */
    public synchronized ProvenanceWriter getProvenanceWriter() {
        if (provenanceWriter == null) {
            provenanceWriter = new ProvenanceWriter(getProvenancePath());
        }
        return provenanceWriter;
    }

    public static String getCcHttpsBase() {
        return CC_HTTPS_BASE;
    }

    public int getNumThreads() {
        return numThreads;
    }

    public void setNumThreads(int numThreads) {
        this.numThreads = numThreads;
    }

    public long getMaxRecords() {
        return maxRecords;
    }

    public void setMaxRecords(long maxRecords) {
        this.maxRecords = maxRecords;
    }

    public long getMaxFilesExtracted() {
        return maxFilesExtracted;
    }

    public void setMaxFilesExtracted(long maxFilesExtracted) {
        this.maxFilesExtracted = maxFilesExtracted;
    }

    public long getMaxFilesTruncated() {
        return maxFilesTruncated;
    }

    public void setMaxFilesTruncated(long maxFilesTruncated) {
        this.maxFilesTruncated = maxFilesTruncated;
    }

    public Path getIndexPathsFile() {
        return indexPathsFile;
    }

    public void setIndexPathsFile(Path indexPathsFile) {
        this.indexPathsFile = indexPathsFile;
    }

    public boolean isDryRun() {
        return dryRun;
    }

    public void setDryRun(boolean dryRun) {
        this.dryRun = dryRun;
    }

    public String getTargetPathPattern() {
        return targetPathPattern;
    }

    public void setTargetPathPattern(String pathPattern) {
        this.targetPathPattern = pathPattern;
    }

    public TargetPathRewriter getTargetPathRewriter() {
        return new TargetPathRewriter(targetPathPattern);
    }

    public RecordSelector getRecordSelector() {
        return recordSelector;
    }

    public void setRecordSelector(RecordSelector recordSelector) {
        this.recordSelector = recordSelector;
    }

    public IndexIterator getIndexIterator() {
        return indexIterator;
    }

    public Fetcher newFetcher() throws TikaConfigException {
        if (fetchConfig == null) {
            fetchConfig = new FetchConfig(null, DEFAULT_THROTTLE_SECONDS, null);
        }
        return fetchConfig.newFetcher();
    }

    public Fetcher newIndexFileFetcher() throws TikaConfigException {
        if (indexFileFetchConfig == null) {
            indexFileFetchConfig = new FetchConfig(null, DEFAULT_THROTTLE_SECONDS, null);
        }
        return indexFileFetchConfig.newFetcher();
    }

    public StreamEmitter newEmitter() throws TikaConfigException {
        if (emitConfig == null) {
            emitConfig = new EmitConfig(DEFAULT_FS_DOCS_PATH);
        }
        return emitConfig.newEmitter();
    }

    public void setExtractTruncated(boolean extractTruncated) {
        this.extractTruncated = extractTruncated;
    }

    public boolean isExtractTruncated() {
        return extractTruncated;
    }

    public String getRunLabel() {
        return runLabel;
    }

    public void setRunLabel(String runLabel) {
        this.runLabel = runLabel;
    }

    public ColumnarIndexConfig getColumnarIndexConfig() {
        return columnarIndexConfig;
    }

    /**
     * Config for {@link CCColumnarIndexExtractor} (the "QueryIndex" command) -- queries Common
     * Crawl's columnar (Parquet) index at
     * s3://commoncrawl/cc-index/table/cc-main/warc/crawl=&lt;crawlGlob&gt;/subset=&lt;subset&gt;/
     * instead of scanning the raw CDX index shard-by-shard. See docs/columnar-index.adoc.
     */
    public static class ColumnarIndexConfig {
        private final String crawlGlob;
        private final String subset;
        private final String where;
        private final String countQuery;
        private final long countTimeoutSeconds;

        @JsonCreator
        public ColumnarIndexConfig(
                @JsonProperty("crawlGlob") String crawlGlob,
                @JsonProperty("subset") String subset,
                @JsonProperty("where") String where,
                @JsonProperty("countQuery") String countQuery,
                @JsonProperty("countTimeoutSeconds") Long countTimeoutSeconds) {
            if (StringUtils.isBlank(crawlGlob)) {
                throw new IllegalArgumentException("columnarIndex.crawlGlob is required");
            }
            if (StringUtils.isBlank(where) && StringUtils.isBlank(countQuery)) {
                throw new IllegalArgumentException(
                        "columnarIndex.where is required (or countQuery for CountIndex)");
            }
            this.crawlGlob = crawlGlob;
            this.subset = StringUtils.isBlank(subset) ? "warc" : subset;
            this.where = where;
            this.countQuery = countQuery;
            this.countTimeoutSeconds =
                    countTimeoutSeconds == null
                            ? DEFAULT_COUNT_TIMEOUT_SECONDS
                            : countTimeoutSeconds;
        }

        public ColumnarIndexConfig(String crawlGlob, String subset, String where) {
            this(crawlGlob, subset, where, null, null);
        }

        /** SQL for CountIndex; "${parquet}" is replaced by the read_parquet(...) source. */
        public String getCountQuery() {
            return countQuery;
        }

        public long getCountTimeoutSeconds() {
            return countTimeoutSeconds;
        }

        public String getCrawlGlob() {
            return crawlGlob;
        }

        public String getSubset() {
            return subset;
        }

        public String getWhere() {
            return where;
        }

        public String getParquetGlobPath() {
            return "s3://"
                    + CC_S3_BUCKET
                    + "/cc-index/table/cc-main/warc/crawl="
                    + crawlGlob
                    + "/subset="
                    + subset
                    + "/*.parquet";
        }
    }

    private static class FetchConfig {
        private final String profile;
        private final long[] throttleSeconds;
        private final String basePath;

        @JsonCreator
        public FetchConfig(
                @JsonProperty("profile") String profile,
                @JsonProperty("throttleSeconds") long[] throttleSeconds,
                @JsonProperty("basePath") String basePath) {
            this.profile = profile;
            this.throttleSeconds =
                    (throttleSeconds == null) ? DEFAULT_THROTTLE_SECONDS : throttleSeconds;
            this.basePath = basePath;
        }

        Fetcher newFetcher() throws TikaConfigException {
            if (profile != null) {
                // single attempt; BackoffS3Fetcher owns the retry ladder
                return BackoffS3Fetcher.wrap(
                        TikaPipes.newCCS3Fetcher(profile, null), throttleSeconds);
            } else if (basePath != null) {
                return TikaPipes.newFileSystemFetcher(basePath);
            }
            return TikaPipes.newBackoffHttpFetcher(throttleSeconds);
        }
    }

    private static class EmitConfig {
        private String profile;
        private String region;
        private String bucket;
        private String prefix;
        private String path;

        private EmitConfig(String path) {
            this.path = path;
        }

        // TODO -- clean this up with different classes
        // for the different fetchers and use jackson's inference
        @JsonCreator
        public EmitConfig(
                @JsonProperty("profile") String profile,
                @JsonProperty("region") String region,
                @JsonProperty("bucket") String bucket,
                @JsonProperty("prefix") String prefix,
                @JsonProperty("path") String path) {
            this.profile = profile;
            this.region = region;
            this.bucket = bucket;
            this.prefix = prefix;
            this.path = path;
        }

        public StreamEmitter newEmitter() throws TikaConfigException {
            if (!StringUtils.isBlank(profile)) {
                if (StringUtils.isBlank(bucket)) {
                    throw new TikaConfigException("Must specify a bucket for docs");
                }
                return TikaPipes.newS3Emitter(
                        profile,
                        bucket,
                        region != null ? region : ExtractorConfig.CC_REGION,
                        StringUtils.isBlank(prefix) ? null : prefix);
            }
            if (StringUtils.isBlank(path)) {
                path = DEFAULT_FS_DOCS_PATH;
            }
            // Auto-create output directory if it doesn't exist
            java.nio.file.Path outputPath = java.nio.file.Paths.get(path);
            if (!java.nio.file.Files.exists(outputPath)) {
                try {
                    java.nio.file.Files.createDirectories(outputPath);
                } catch (java.io.IOException e) {
                    throw new TikaConfigException("Could not create output directory: " + path, e);
                }
            }
            return TikaPipes.newFileSystemEmitter(path);
        }
    }
}
